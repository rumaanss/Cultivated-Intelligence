local w=Metrics.new(4)
assert(Metrics.summary(w)==nil)
for _,n in {10,20,30,40,50}do Metrics.push(w,n)end
Metrics.push(w,0/0);Metrics.push(w,-1);Metrics.push(w,math.huge)
local p50,p95,p99=Metrics.summary(w)
assert(#w.values==4 and p50==30 and p95==50 and p99==50)
local track=Interpolation.new()
Interpolation.push(track,1,Vector3.new(0,0,0),0)
Interpolation.push(track,1,Vector3.new(0,0,0),0)
assert(#track.samples==1,"Repeated snapshots create false samples")
Interpolation.push(track,1.2,Vector3.new(2,0,0),0)
assert(math.abs(Interpolation.sample(track,1.1).X-1)<.0001)
Interpolation.push(track,1.3,Vector3.new(3,0,0),1)
assert(#track.samples==1,"Authoritative warp must reset interpolation")
print("PASS bounded percentile window and repeated-snapshot interpolation")
