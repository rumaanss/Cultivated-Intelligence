--!strict
-- Explicit Studio Command Bar operation. Reads existing terrain; never edits it.
local M={}
local Island=require(script.Parent.IslandConfig)
local loadModule=require :: (ModuleScript)->any
function M.Upload()
 local RunService=game:GetService("RunService");assert(RunService:IsStudio() and not RunService:IsRunning(),"Run in Studio with Play stopped")
 local source=game:GetService("ServerScriptService"):FindFirstChild("Server");assert(source~=nil)
 local cfg=source:FindFirstChild("LiveTransportConfig");assert(cfg~=nil and cfg:IsA("ModuleScript"),"Sync server transport config first")
 local transport=loadModule(cfg)
 assert(type(transport.Url)=="string" and string.match(transport.Url,"/exchange$") and type(transport.Token)=="string" and #transport.Token>=32,"Invalid server transport config; regenerate it with relay --roblox-root and sync it into Studio")
 local terrain=workspace:FindFirstChildOfClass("Terrain");assert(terrain~=nil and terrain:IsA("Terrain"))
 local params=RaycastParams.new();params.FilterType=Enum.RaycastFilterType.Include;params.FilterDescendantsInstances={terrain};params.IgnoreWater=false
 local originX,originZ,cell=Island.MinX,Island.MinZ,32
 local width,height=(Island.MaxX-Island.MinX)/cell,(Island.MaxZ-Island.MinZ)/cell
 assert(width%1==0 and height%1==0,"Island dimensions must align to surface cells")
 local Http=game:GetService("HttpService")
 local revision="island-"..string.gsub(Http:GenerateGUID(false),"-","")
 local lines={string.format("CIPLANTSURFACE1 %s %d %d %d %d %d",revision,width,height,originX,originZ,cell)}
 local validCount=0
 for z=0,height-1 do
  for x=0,width-1 do
   local wx,wz=originX+(x+.5)*cell,originZ+(z+.5)*cell
   local hit=workspace:Raycast(Vector3.new(wx,300,wz),Vector3.new(0,-500,0),params)
   local valid=hit~=nil and hit.Material~=Enum.Material.Water and hit.Position.Y>2 and hit.Normal.Y>.7 and not (math.abs(wx)<110 and math.abs(wz)<100)
   if valid then validCount+=1 end
   table.insert(lines,string.format("%.8f 8 20 8 %d",if hit then hit.Position.Y else -64,if valid then 1 else 0))
  end
 end
 assert(validCount>0,"No plantable terrain found; build island first")
 local url=string.gsub(transport.Url,"/exchange$","/plant-surface")
 local result=Http:RequestAsync({Url=url,Method="POST",Headers={["Content-Type"]="application/json",["X-CI-Token"]=transport.Token},Body=Http:JSONEncode({text=table.concat(lines,"\n").."\n"})})
 if result.StatusCode==401 then
  error("Surface upload was rejected by the relay (HTTP 401). Sync ServerScriptService.Server.LiveTransportConfig generated by the currently running relay for this world directory, then retry with Play stopped. No surface file was saved.")
 end
 assert(result.Success,"Surface export HTTP "..result.StatusCode..": "..string.sub(result.Body,1,200))
 print("[Plants] Exported "..validCount.." plantable cells. Start cybernet_sim with --island-surface pointing to this relay directory\'s plant_surface.txt. A restored world retains its checkpoint terrain.")
 return revision
end
return M
