"""Generate identical component IDs and rest hierarchy for C++ and Roblox.
A body component is a joint group, never a decorative Part. Schema is additive;
existing snapshot/command messages are not changed by this generator.
"""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[2]
designs=json.loads((ROOT/'assets/agents/designs.json').read_text())
manifest={'version':1,'coordinates':'right-handed, Y up, forward -Z','angles':'radians','units':'model units; multiply pivots by radius/safeRadius','designs':[]}
for di,d in enumerate(designs,1):
 manifest['designs'].append({'id':di,'key':d['key'],'safeRadius':d['safeRadius'],'components':[{'id':i+1,'name':j['name'],'parent':j['parent'],'pivot':j['pivot'],'axis':j['axis']} for i,j in enumerate(d['joints'])]})
(ROOT/'assets/agents/body_contract.json').write_text(json.dumps(manifest,indent=2)+'\n')
def lua(x):
 if isinstance(x,dict):return '{'+','.join('['+json.dumps(k)+']='+lua(v) for k,v in x.items())+'}'
 if isinstance(x,list):return '{'+','.join(map(lua,x))+'}'
 return json.dumps(x)
(ROOT/'src/shared/AgentBodyContract.lua').write_text('--!strict\n-- Generated by tools/agents/build_body_contract.py. IDs are versioned.\nreturn '+lua(manifest)+'\n')
header=['#pragma once','#include <array>','#include <cstdint>','namespace ci::body {','inline constexpr std::uint16_t schema_version=1;','struct Component { std::uint16_t id,parent; const char* name; std::array<double,3> pivot,axis; };','struct Design { std::uint16_t id; const char* key; double safe_radius; const Component* components; std::uint16_t count; };']
for d in manifest['designs']:
 header.append('inline constexpr Component '+d['key']+'[] = {')
 for j in d['components']:header.append('{'+str(j['id'])+','+str(j['parent'])+','+json.dumps(j['name'])+',{'+','.join(map(str,j['pivot']))+'},{'+','.join(map(str,j['axis']))+'}},')
 header.append('};')
header.append('inline constexpr Design designs[] = {')
for d in manifest['designs']:header.append('{'+str(d['id'])+','+json.dumps(d['key'])+','+str(d['safeRadius'])+','+d['key']+','+str(len(d['components']))+'},')
header+=['};','inline constexpr const Design* find(std::uint16_t id) { for(const auto& d:designs) if(d.id==id) return &d; return nullptr; }','} // namespace ci::body']
out=ROOT/'assets/agents/cpp';out.mkdir(exist_ok=True)
(out/'agent_body_contract.hpp').write_text('\n'.join(header)+'\n')
print('Generated shared contract: 6 bodies, stable IDs, joint hierarchy and rest axes')
