#!/usr/bin/env python3
"""Compile the one canonical geometry definition into a C++ header. Python 3.10+."""
import argparse,hashlib,json,math,re
from pathlib import Path

def need(ok,message):
    if not ok:raise ValueError(message)
def finite(x):return type(x) in (int,float) and math.isfinite(x)
def validate(g,with_hash=False):
    need(type(g)==dict,'Invalid geometry fields')
    keys={'version','revision','bounds','bodyRadius','objects'}|({'terrain'} if g.get('version')==2 else set())|({'sha256'} if with_hash else set())
    need(type(g)==dict and set(g)==keys,'Invalid geometry fields')
    need(type(g['version'])==int and g['version'] in (1,2),'Unsupported geometry version')
    need(type(g['revision'])==str and re.fullmatch(r'[A-Za-z0-9_-]{1,48}',g['revision']),'Invalid revision')
    need(g['bounds']==[100,100,60],'Unsupported bounds')
    r=g['bodyRadius'];need(finite(r) and 0<r<=1,'Invalid body radius')
    need(type(g['objects'])==list and 1<=len(g['objects'])<=128,'Invalid object count')
    last=0
    for o in g['objects']:
        need(type(o)==dict and set(o)=={'id','shape','center','halfSize','solid','opaque','material'},'Invalid object fields')
        need(type(o['id'])==int and last<o['id']<=4294967295,'Object IDs must be sorted and unique');last=o['id']
        need(o['shape'] in ('box','sphere') and o['material'] in ('Rock','Slate','Sand'),'Unsupported shape/material')
        for k in ('center','halfSize'):need(type(o[k])==list and len(o[k])==3 and all(finite(x) for x in o[k]),'Invalid vector')
        need(type(o['solid'])==bool and type(o['opaque'])==bool,'Invalid flags')
        need(all(e>0 and c-e>=2*r and c+e<=b-2*r for c,e,b in zip(o['center'],o['halfSize'],g['bounds'])),'Object outside body-safe basin')
        if o['shape']=='sphere':need(o['halfSize'][0]==o['halfSize'][1]==o['halfSize'][2],'Sphere requires equal radii')
    if g['version']==2:
        t=g['terrain'];need(type(t)==dict and set(t)=={'planes'},'Invalid terrain fields')
        need(type(t['planes'])==list and 1<=len(t['planes'])<=8,'Invalid terrain plane count')
        for p in t['planes']:
            need(type(p)==list and len(p)==3 and all(finite(x) for x in p),'Invalid terrain plane')
            need(abs(p[0])<=3 and abs(p[1])<=3,'Terrain slope too steep')
        need(len({tuple(p) for p in t['planes']})==len(t['planes']),'Duplicate terrain plane')
        need(any(p[0]==0 and p[1]==0 and p[2]>=1 for p in t['planes']),'Terrain needs a positive base plane')
        for x in (0,100):
            for y in (0,100):
                need(max(a*x+b*y+c+r*math.sqrt(1+a*a+b*b) for a,b,c in t['planes'])<55,'Terrain lacks surface clearance')
        # Rocks must sit entirely above the floor; projection then cannot be trapped.
        for o in g['objects']:
            for a,b,c in t['planes']:
                support=(o['halfSize'][0]*math.sqrt(1+a*a+b*b) if o['shape']=='sphere' else abs(a)*o['halfSize'][0]+abs(b)*o['halfSize'][1]+o['halfSize'][2])
                need(o['center'][2]-a*o['center'][0]-b*o['center'][1]-c>=support-1e-6,'Rock penetrates terrain')
    # Conservative non-overlap rule keeps initial depenetration well-defined.
    for i,a in enumerate(g['objects']):
        for b in g['objects'][i+1:]:
            if a['solid'] and b['solid']:
                need(any(abs(x-y)>ex+ey+2*r+0.001 for x,y,ex,ey in zip(a['center'],b['center'],a['halfSize'],b['halfSize'])),'Solid proxies need a body-width gap')
    if with_hash:
        unsigned={k:v for k,v in g.items() if k!='sha256'}
        need(g['sha256']==digest(unsigned),'Geometry checksum mismatch')
    return g

def digest(g):return hashlib.sha256(json.dumps(g,sort_keys=True,separators=(',',':'),ensure_ascii=True).encode()).hexdigest()
def generate(g,namespace='shared_geometry'):
    validate(g);g=dict(g,sha256=digest(g));rows=[]
    vec=lambda xs:'{'+','.join(repr(float(x))+'F' for x in xs)+'}'
    for o in g['objects']:
        rows.append('    {'+str(o['id'])+'U,GeometryShape::'+('Box' if o['shape']=='box' else 'Sphere')+','+vec(o['center'])+','+vec(o['halfSize'])+','+str(o['solid']).lower()+','+str(o['opaque']).lower()+'}')
    return '#pragma once\n// Generated by tools/generate_geometry.py; edit config/shared_geometry.json.\n#include "cybernet/world/geometry.hpp"\n#include <array>\nnamespace cybernet::'+namespace+' {\ninline constexpr float BodyRadius = '+repr(float(g['bodyRadius']))+'F;\ninline constexpr const char* Revision = '+json.dumps(g['revision'])+';\ninline constexpr std::array<GeometryObject,'+str(len(rows))+'> Objects{{\n'+',\n'.join(rows)+'\n}};\ninline constexpr std::array<Vec3,'+str(len(g.get('terrain',{}).get('planes',[])))+'> Planes{{'+','.join(vec(p) for p in g.get('terrain',{}).get('planes',[]))+'}};\ninline constexpr const char* Json = R"CI_GEOMETRY('+json.dumps(g,sort_keys=True,separators=(',',':'))+')CI_GEOMETRY";\n}\n'
if __name__=='__main__':
    root=Path(__file__).resolve().parents[1];p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    try:
        for name,config in [('shared_geometry','shared_geometry'),('lake_geometry','lake_geometry')]:
            text=generate(json.loads((root/('config/'+config+'.json')).read_text()),name);out=root/('include/cybernet/world/'+name+'_generated.hpp')
            if a.check:need(out.exists() and out.read_text()==text,'Generated geometry is stale; run tools/generate_geometry.py')
            else:out.write_text(text,encoding='utf-8')
        print('Shared geometry verified' if a.check else 'Shared geometry header generated')
    except (ValueError,OSError) as e:p.exit(1,str(e)+'\n')
